#!/usr/bin/env python3
"""XLT's interface sounds, synthesised (no samples, no numpy).

The logo's four cards are four notes (A5 C#6 E6 A6, an A-major arpeggio of soft
bell tones): the boot screen plays one as each card pops in, and starting a
game plays them quickly. Everything else is short and quiet, pitched where the
PSP's small speakers sound clean (roughly 500 Hz - 3 kHz).

    bake_sounds.py OUT.h [DEMO.wav]   -> 44.1 kHz mono int16 arrays, and all of them in a row to listen to
"""
import math
import random
import struct
import sys
import wave

RATE = 44100
A5, CS6, E6, A6 = 880.0, 1108.73, 1318.51, 1760.0
NOTES = (A5, CS6, E6, A6)  # triangle, circle, cross, square


def silence(sec):
    return [0.0] * int(RATE * sec)


def env(t, attack, decay):
    """Raised-cosine attack, exponential decay."""
    a = 0.5 - 0.5 * math.cos(math.pi * t / attack) if t < attack else 1.0
    return a * math.exp(-max(0.0, t - attack) / decay)


def bell(f, dur, decay, partials=((1, 1.0), (2.0, 0.22), (3.01, 0.06))):
    out = []
    for n in range(int(RATE * dur)):
        t = n / RATE
        v = sum(a * math.sin(2 * math.pi * f * m * t) for m, a in partials)
        out.append(v * env(t, 0.002, decay))
    return out


def tick(f, dur, decay, drop=0.25):
    """A tiny sine blip whose pitch falls a little at the start (a soft 'tock', not a beep)."""
    out, ph = [], 0.0
    for n in range(int(RATE * dur)):
        t = n / RATE
        ph += 2 * math.pi * f * (1 + drop * math.exp(-t / 0.003)) / RATE
        out.append(math.sin(ph) * env(t, 0.0008, decay))
    return out


def noise(dur, decay, lp=0.35, attack=0.001, seed=1):
    rnd, y, out = random.Random(seed), 0.0, []
    for n in range(int(RATE * dur)):
        y += lp * (rnd.uniform(-1, 1) - y)  # one-pole low-pass
        out.append(y * env(n / RATE, attack, decay))
    return out


def glide(f0, f1, dur, decay):
    out, ph = [], 0.0
    for n in range(int(RATE * dur)):
        t = n / RATE
        f = f0 + (f1 - f0) * min(1.0, t / dur)
        ph += 2 * math.pi * f / RATE
        out.append(math.sin(ph) * env(t, 0.006, decay))
    return out


def mix(*parts):
    """parts: (start seconds, samples, gain)."""
    n = max(int(s * RATE) + len(p) for s, p, _ in parts)
    out = [0.0] * n
    for s, p, g in parts:
        o = int(s * RATE)
        for i, v in enumerate(p):
            out[o + i] += v * g
    return out


def norm(x, peak):
    m = max(1e-9, max(abs(v) for v in x))
    return [v * peak / m for v in x]


def fade_tail(x, sec=0.004):
    k = min(len(x), int(RATE * sec))
    for i in range(k):
        x[len(x) - k + i] *= (k - i) / k
    return x


SOUNDS = {}


def sound(name, samples, peak):
    SOUNDS[name] = fade_tail(norm(samples, peak))


# the logo's notes, one per shape (boot screen)
for i, f in enumerate(NOTES):
    sound(f"NOTE{i}", bell(f, 0.7, 0.2), 0.16)
sound("MOVE", tick(1568, 0.030, 0.006), 0.11)                        # one step in a list
sound("KEY", mix((0, tick(1480, 0.022, 0.0035, 0.12), 1), (0, noise(0.008, 0.0015, 0.5, 0.0003, 4), 0.25)), 0.085)  # typing
sound("DEL", mix((0, tick(1050, 0.026, 0.0045, 0.12), 1), (0, noise(0.008, 0.0015, 0.5, 0.0003, 5), 0.2)), 0.08)
sound("CARD", mix((0, tick(1175, 0.05, 0.012), 1), (0, tick(2350, 0.03, 0.006), 0.25)), 0.14)  # another category
sound("SELECT", mix((0, bell(E6, 0.16, 0.05), 1), (0.045, bell(A6, 0.2, 0.06), 0.9)), 0.17)     # ✕
sound("BACK", mix((0, bell(A6, 0.12, 0.04), 0.8), (0.04, bell(E6, 0.16, 0.05), 1)), 0.14)      # ○
sound("OPEN", mix((0, glide(660, 990, 0.09, 0.05), 1), (0, noise(0.08, 0.03, 0.08), 0.5)), 0.13)  # a sheet slides in
sound("CLOSE", mix((0, glide(990, 660, 0.08, 0.04), 1), (0, noise(0.07, 0.025, 0.08), 0.4)), 0.11)
sound("ON", mix((0, tick(1760, 0.04, 0.008, 0.1), 1), (0.03, tick(2637, 0.04, 0.008, 0.1), 0.8)), 0.14)
sound("OFF", mix((0, tick(1760, 0.04, 0.008, 0.1), 0.8), (0.03, tick(1175, 0.05, 0.01, 0.1), 1)), 0.13)
sound("LAUNCH", mix(*[(i * 0.06, bell(f, 0.5, 0.12), 1 - i * 0.08) for i, f in enumerate(NOTES)],
                    (0.24, bell(A6 * 2, 0.35, 0.1), 0.15)), 0.2)      # the logo's notes, quickly
sound("SHUTTER", mix((0, noise(0.03, 0.006, 0.6, 0.0005, 2), 1), (0.045, noise(0.04, 0.01, 0.5, 0.0005, 3), 0.8)), 0.2)
sound("ERROR", mix((0, tick(523, 0.09, 0.03, 0.05), 1), (0.07, tick(494, 0.12, 0.04, 0.05), 1)), 0.14)


def to_i16(x):
    return [max(-32767, min(32767, int(round(v * 32767)))) for v in x]


def write_header(path):
    with open(path, "w") as f:
        f.write("/* Generated by tools/bake_sounds.py: XLT's interface sounds, 44.1 kHz mono. */\n")
        f.write("#include <stdint.h>\n")
        for name, x in SOUNDS.items():
            d = to_i16(x)
            f.write(f"static const int16_t sfx_{name.lower()}[{len(d)}] = {{\n")
            for k in range(0, len(d), 16):
                f.write(",".join(str(v) for v in d[k:k + 16]) + ",\n")
            f.write("};\n")
        f.write("#define SFX_TABLE \\\n")
        f.write(" \\\n".join(f"    {{sfx_{n.lower()}, {len(SOUNDS[n])}}}," for n in SOUNDS) + "\n")
        f.write('#include "sfx_ids.h"\n')


def write_demo(path):
    seq = []
    for name in ("NOTE0", "NOTE1", "NOTE2", "NOTE3"):
        seq += SOUNDS[name][: int(RATE * 0.267)]  # as the boot screen spaces them
    seq += SOUNDS["NOTE3"][int(RATE * 0.267):] + silence(0.4)
    for name in ("KEY", "KEY", "KEY", "KEY", "DEL", "DEL"):
        seq += SOUNDS[name] + silence(0.14)  # typing speed
    seq += silence(0.3)
    for name in ("MOVE", "MOVE", "MOVE", "CARD", "CARD", "SELECT", "BACK", "OPEN", "CLOSE", "ON", "OFF",
                 "LAUNCH", "SHUTTER", "ERROR"):
        seq += SOUNDS[name] + silence(0.35)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(struct.pack(f"<{len(seq)}h", *to_i16(seq)))


def write_ids(path):
    with open(path, "w") as f:
        f.write("/* Generated by tools/bake_sounds.py with sfx_data.h. */\n#ifndef SFX_IDS_H\n#define SFX_IDS_H\n")
        f.write("enum { " + ", ".join(f"SFX_{n}" for n in SOUNDS) + ", SFX_COUNT };\n#endif\n")


if __name__ == "__main__":
    write_header(sys.argv[1])
    write_ids(sys.argv[1].replace("sfx_data.h", "sfx_ids.h"))
    if len(sys.argv) > 2:
        write_demo(sys.argv[2])
