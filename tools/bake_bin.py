#!/usr/bin/env python3
"""A file as a C array: bake_bin.py IN NAME OUT.h -> static const unsigned char NAME[] = {...};"""
import sys

src, name, out = sys.argv[1:4]
data = open(src, "rb").read()
with open(out, "w") as f:
    f.write(f"/* Generated by tools/bake_bin.py from {src} - do not edit. */\n")
    f.write(f"static const unsigned char {name}[{len(data)}] __attribute__((aligned(16))) = {{\n")
    for i in range(0, len(data), 24):
        f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
