#!/usr/bin/env python3
"""Bake the second icon texture (the main atlas is full): the web browser's
icons and the control center's power dialog. A 128x128 GU_PSM_4444
texture, white + alpha, tinted at draw time, swizzled like the atlas.

Usage: bake_webicons.py OUT_HEADER [PREVIEW_PNG]
"""
import sys
from PIL import Image, ImageDraw

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from bake_atlas import Shelf, swizzle4444, canvas, finish, icon_usb  # noqa: E402

TEX_W, TEX_H = 128, 128


def globe(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .075), 2)
    m = w * .08
    d.ellipse([m, m, w - m, w - m], outline=255, width=lw)
    d.ellipse([w * .3, m, w * .7, w - m], outline=255, width=lw)  # a meridian
    d.line([(m, w * .5), (w - m, w * .5)], fill=255, width=lw)   # the equator
    for y in (.29, .71):                                          # two parallels
        half = ((.42 ** 2 - (y - .5) ** 2) ** .5) * w
        d.line([(w * .5 - half + lw / 2, w * y), (w * .5 + half - lw / 2, w * y)], fill=255, width=lw)
    return finish(img, size)


def lock(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .14), 2)
    d.arc([w * .25, w * .06, w * .75, w * .62], 180, 360, fill=255, width=lw)
    d.line([(w * .25 + lw / 2, w * .34), (w * .25 + lw / 2, w * .5)], fill=255, width=lw)
    d.line([(w * .75 - lw / 2, w * .34), (w * .75 - lw / 2, w * .5)], fill=255, width=lw)
    d.rounded_rectangle([w * .14, w * .46, w * .86, w * .96], radius=w * .1, fill=255)
    return finish(img, size)


def arrow(size, left):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .13), 2)
    pts = [(w * .62, w * .2), (w * .3, w * .5), (w * .62, w * .8)]
    if not left:
        pts = [(w - x, y) for x, y in pts]
    d.line(pts, fill=255, width=lw, joint="curve")
    return finish(img, size)


def reload(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .12), 2)
    d.arc([w * .16, w * .16, w * .84, w * .84], 300, 230, fill=255, width=lw)
    # the arrow head at the arc's end (top right)
    d.polygon([(w * .62, w * .06), (w * .9, w * .2), (w * .66, w * .4)], fill=255)
    return finish(img, size)


def text_lines(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .11), 2)
    for i, y in enumerate((.24, .44, .64, .84)):
        d.line([(w * .14, w * y), (w * (.86 if i < 3 else .6), w * y)], fill=255, width=lw)
    return finish(img, size)


def power(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .11), 2)
    d.arc([w * .14, w * .18, w * .86, w * .9], 300, 240, fill=255, width=lw)  # open at the top
    d.line([(w * .5, w * .06), (w * .5, w * .48)], fill=255, width=lw)
    return finish(img, size)


def leave(size):
    """Exit to the XMB: an open frame and an arrow going out of it."""
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .1), 2)
    d.line([(w * .52, w * .14), (w * .14, w * .14), (w * .14, w * .86), (w * .52, w * .86)], fill=255, width=lw,
           joint="curve")
    d.line([(w * .36, w * .5), (w * .86, w * .5)], fill=255, width=lw)
    d.line([(w * .68, w * .3), (w * .88, w * .5), (w * .68, w * .7)], fill=255, width=lw, joint="curve")
    return finish(img, size)


def cross(size):
    img, d, s = canvas(size)
    w = size * s
    lw = max(int(w * .11), 2)
    d.line([(w * .24, w * .24), (w * .76, w * .76)], fill=255, width=lw)
    d.line([(w * .76, w * .24), (w * .24, w * .76)], fill=255, width=lw)
    return finish(img, size)


ICONS = [  # (C name, painter, size)
    ("WICON_GLOBE", globe, 40),
    ("WICON_GLOBE_S", globe, 20),
    ("WICON_LOCK", lock, 12),
    ("WICON_BACK", lambda n: arrow(n, True), 16),
    ("WICON_FWD", lambda n: arrow(n, False), 16),
    ("WICON_RELOAD", reload, 16),
    ("WICON_TEXT", text_lines, 16),
    # the control center's power dialog (web.h names them WEB_ICON_POWER...)
    ("WICON_POWER", power, 32),
    ("WICON_RESTART", reload, 32),
    ("WICON_EXIT", leave, 32),
    ("WICON_CANCEL", cross, 32),
    # the USB mode screen's big symbol: the atlas's own shape, drawn at its size (scaling 20 px up blurs)
    ("WICON_USB", icon_usb, 48),
]


def main():
    out = sys.argv[1]
    preview = sys.argv[2] if len(sys.argv) > 2 else None
    tex = Image.new("L", (TEX_W, TEX_H), 0)
    shelf = Shelf(TEX_W, TEX_H)
    rows = []
    for name, painter, size in sorted(ICONS, key=lambda t: -t[2]):
        im = painter(size)
        x, y = shelf.place(size, size)
        tex.paste(im, (x, y))
        rows.append((name, x, y, size))
    order = [n for n, _, _ in ICONS]
    rows.sort(key=lambda r: order.index(r[0]))
    if preview:
        tex.save(preview)
    sw = swizzle4444(tex)
    with open(out, "w") as f:
        f.write("/* Generated by tools/bake_webicons.py - do not edit. */\n")
        f.write("#ifndef WEBICON_DATA_H\n#define WEBICON_DATA_H\n\n")
        f.write(f"#define WEBICON_W {TEX_W}\n#define WEBICON_H {TEX_H}\n\nenum {{\n")
        for name, *_ in rows:
            f.write(f"    {name},\n")
        f.write("    WICON_COUNT\n};\n\n")
        f.write("static const short webicon_rects[WICON_COUNT][3] = {\n")
        for name, x, y, size in rows:
            f.write(f"    {{{x}, {y}, {size}}}, /* {name} */\n")
        f.write("};\n\n")
        f.write("static const unsigned char webicon_pixels[] __attribute__((aligned(16))) = {\n")
        for i in range(0, len(sw), 24):
            f.write("    " + ",".join(str(b) for b in sw[i:i + 24]) + ",\n")
        f.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
