#!/usr/bin/env python3
"""Bake the root certificates the web browser trusts into a C header: every
certificate of the PC's CA bundle (Mozilla's list, as the distribution ships
it), as DER, one after another, with their lengths.

Usage: bake_cacerts.py OUT_HEADER [BUNDLE]
"""
import base64
import re
import sys


def main():
    out = sys.argv[1]
    bundle = sys.argv[2] if len(sys.argv) > 2 else "/etc/ssl/certs/ca-certificates.crt"
    pem = open(bundle, encoding="ascii", errors="replace").read()
    ders = [base64.b64decode(m) for m in
            re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S)]
    if not ders:
        raise SystemExit("no certificates in " + bundle)
    blob = b"".join(ders)
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/bake_cacerts.py from {bundle} - do not edit. */\n")
        f.write("#ifndef CACERTS_DATA_H\n#define CACERTS_DATA_H\n\n")
        f.write(f"#define CACERT_COUNT {len(ders)}\n")
        f.write("static const unsigned short cacert_len[CACERT_COUNT] = {\n")
        for i in range(0, len(ders), 12):
            f.write("    " + ", ".join(str(len(d)) for d in ders[i:i + 12]) + ",\n")
        f.write("};\n\nstatic const unsigned char cacert_der[] = {\n")
        for i in range(0, len(blob), 24):
            f.write("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",\n")
        f.write("};\n\n#endif\n")
    print(f"cacerts: {len(ders)} certificates, {len(blob)} bytes")


if __name__ == "__main__":
    main()
