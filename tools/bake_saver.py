#!/usr/bin/env python3
"""Bake the screensaver's texture offline.

Two textures (white + alpha, tinted by vertex colour), drawn from main RAM
while the screensaver is up:
  * 256-wide GU_PSM_4444: the clock face, '0'-'9' and ':' in Noto Sans Light
  * 64x64 GU_PSM_8888, linear: a soft glow for the drifting background lights
    (8-bit alpha: 4-bit alpha shows rings when it is stretched over the screen)
Also a 256-entry sine table (Q12), so the animation needs no floats.

Usage: bake_saver.py OUT_HEADER [PREVIEW_PNG]
"""
import math
import sys
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from bake_atlas import Shelf, swizzle4444  # noqa: E402

TEX_W, TEX_H = 256, 256
FONT = "/usr/share/fonts/noto/NotoSans-Light.ttf"
PX = 84
CHARS = "0123456789:"
GLOW = 64


def glow():
    img = Image.new("L", (GLOW, GLOW), 0)
    px = img.load()
    c = (GLOW - 1) / 2
    for y in range(GLOW):
        for x in range(GLOW):
            r = math.hypot(x - c, y - c) / c
            # smooth falloff that reaches exactly 0 at the edge (no visible rim)
            a = max(0.0, 1.0 - r) ** 2 * (3 - 2 * max(0.0, 1.0 - r)) if r < 1 else 0.0
            px[x, y] = int(round(255 * a))
    return img


def main():
    out_h = sys.argv[1]
    preview = sys.argv[2] if len(sys.argv) > 2 else None
    font = ImageFont.truetype(FONT, PX)
    ascent, descent = font.getmetrics()
    items, meta = {}, []
    for ch in CHARS:
        adv = int(round(font.getlength(ch)))
        pad = 8
        canvas = Image.new("L", (adv + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(canvas).text((pad, pad), ch, font=font, fill=255)
        box = canvas.getbbox()
        g = canvas.crop(box)
        items[ch] = g
        meta.append((ch, g.size[0], g.size[1], box[0] - pad, box[1] - pad, adv))

    tex = Image.new("L", (TEX_W, TEX_H), 0)
    shelf = Shelf(TEX_W, TEX_H)
    pos = {}
    for tag, img in sorted(items.items(), key=lambda kv: (-kv[1].size[1], -kv[1].size[0])):
        x, y = shelf.place(*img.size)
        tex.paste(img, (x, y))
        pos[tag] = (x, y)
    tex_h = TEX_H
    while tex_h // 2 >= shelf.y + shelf.row_h:  # crop to the power of two that holds it
        tex_h //= 2
    tex = tex.crop((0, 0, TEX_W, tex_h))
    if preview:
        tex.save(preview)

    sw = swizzle4444(tex)
    # digit height (top of '0' to its baseline) for vertical centring
    digit_top = meta[0][4]
    with open(out_h, "w") as f:
        f.write("/* Generated by tools/bake_saver.py - do not edit. */\n")
        f.write("/* Glyphs rendered from Noto Sans Light (SIL Open Font License 1.1). */\n")
        f.write("#ifndef SAVER_DATA_H\n#define SAVER_DATA_H\n\n")
        f.write(f"#define SAVER_TEX_W {TEX_W}\n#define SAVER_TEX_H {tex_h}\n")
        f.write(f"#define SAVER_GLOW_SIZE {GLOW}\n")
        f.write(f"#define SAVER_DIGIT_TOP {digit_top}  /* ink top below the line top */\n")
        f.write(f"#define SAVER_DIGIT_H {meta[0][2]}\n")
        f.write(f"#define SAVER_LINE_H {ascent + descent}\n\n")
        f.write("/* '0'..'9' then ':' -- x, y, w, h, ox, oy, adv (Glyph, from gfx.h) */\n")
        f.write(f"static const Glyph saver_glyphs[{len(CHARS)}] = {{\n")
        for ch, w, h, ox, oy, adv in meta:
            x, y = pos[ch]
            f.write(f"    {{{x}, {y}, {w}, {h}, {ox}, {oy}, {adv}}}, /* '{ch}' */\n")
        f.write("};\n\n")
        f.write("/* sin(2*pi*i/256) in Q12 */\nstatic const short saver_sin[256] = {\n")
        vals = [int(round(4096 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
        for i in range(0, 256, 16):
            f.write("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const unsigned char saver_pixels[] __attribute__((aligned(16))) = {\n")
        for i in range(0, len(sw), 24):
            f.write("    " + ",".join(str(b) for b in sw[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write("/* the glow, 8888 (white, alpha), not swizzled */\n")
        f.write("static const unsigned char saver_glow[] __attribute__((aligned(16))) = {\n")
        g = glow().load()
        row = []
        for y in range(GLOW):
            for x in range(GLOW):
                row += [255, 255, 255, g[x, y]]
        for i in range(0, len(row), 32):
            f.write("    " + ",".join(str(b) for b in row[i:i + 32]) + ",\n")
        f.write("};\n\n#endif\n")
    print(f"saver: {len(CHARS)} glyphs, shelf ended at y={shelf.y + shelf.row_h}")


if __name__ == "__main__":
    main()
